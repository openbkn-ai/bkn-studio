import { http } from "@/framework/request/http";
import { readErrorCode, readErrorDetails } from "@/framework/request/error-message";
import type {
  ValueType,
  ValueTypeInput,
  ValueTypeReference,
} from "@/modules/knowledge-network/types/knowledge-network";
import type {
  BackendListResponse,
  BackendValueType,
} from "@/modules/knowledge-network/services/mappers/backend-types";
import {
  mapValueType,
  parseValueTypeReferences,
  toBackendValueTypeInput,
} from "@/modules/knowledge-network/services/mappers/value-type.mapper";
import {
  mockObjectTypeDataProperties,
  mockObjectTypes,
} from "@/modules/knowledge-network/services/mock/state";
import { mockValueTypes } from "@/modules/knowledge-network/services/mock/value-types";
import {
  formatTimestamp,
  useMock,
  wait,
} from "@/modules/knowledge-network/services/shared/runtime";

const VALUE_TYPE_REFERENCED_CODE = "BknBackend.ValueType.Referenced";

/**
 * A delete, or a `base_type` change, refused because data properties still name the value type.
 * `references` lists them.
 */
export class ValueTypeReferencedError extends Error {
  readonly isValueTypeReferenced = true as const;

  constructor(
    message: string,
    readonly references: ValueTypeReference[],
  ) {
    super(message);
    this.name = "ValueTypeReferencedError";
  }
}

function rethrowValueTypeError(error: unknown): never {
  if (readErrorCode(error) === VALUE_TYPE_REFERENCED_CODE) {
    throw new ValueTypeReferencedError(
      VALUE_TYPE_REFERENCED_CODE,
      parseValueTypeReferences(readErrorDetails(error)),
    );
  }
  throw error;
}

const valueTypesPath = (networkId: string) =>
  `/bkn-backend/v1/knowledge-networks/${encodeURIComponent(networkId)}/value-types`;

/** Every value type of the network, by name. */
export async function listKnowledgeNetworkValueTypes(networkId: string): Promise<ValueType[]> {
  if (useMock) {
    return wait(
      [...(mockValueTypes[networkId] ?? [])].sort((left, right) =>
        left.name.localeCompare(right.name),
      ),
    );
  }

  // Each caller says itself when the list does not load.
  const response = await http.get<BackendListResponse<BackendValueType>>(
    valueTypesPath(networkId),
    {
      params: { direction: "asc", limit: -1, sort: "name" },
      skipErrorToast: true,
    },
  );
  return (response.data.entries ?? []).map(mapValueType);
}

function mockReferences(networkId: string, valueTypeId: string): ValueTypeReference[] {
  const names = new Map((mockObjectTypes[networkId] ?? []).map((item) => [item.id, item.name]));
  return Object.entries(mockObjectTypeDataProperties[networkId] ?? {}).flatMap(
    ([objectTypeId, properties]) =>
      properties
        .filter((property) => property.declarations?.constraints?.valueType === valueTypeId)
        .map((property) => ({
          objectTypeId,
          objectTypeName: names.get(objectTypeId) ?? objectTypeId,
          property: property.name,
          propertyType: property.type,
        })),
  );
}

function saveMock(networkId: string, id: string, input: ValueTypeInput) {
  const next: ValueType = {
    ...input,
    id,
    updateTime: formatTimestamp(Date.now()),
    updaterName: "Local Admin",
  };
  const list = mockValueTypes[networkId] ?? [];
  mockValueTypes[networkId] = list.some((item) => item.id === id)
    ? list.map((item) => (item.id === id ? next : item))
    : [next, ...list];
}

/** Creates a value type and returns its ID, generated by the backend when the input has none. */
export async function createKnowledgeNetworkValueType(
  networkId: string,
  input: ValueTypeInput,
): Promise<string> {
  if (useMock) {
    const id = input.id || `vt_${Date.now().toString(36)}`;
    saveMock(networkId, id, input);
    return wait(id);
  }

  const response = await http.post<Array<{ id?: string }>>(
    valueTypesPath(networkId),
    { entries: [toBackendValueTypeInput(input)] },
    { skipErrorToast: true },
  );
  return response.data?.[0]?.id ?? input.id ?? "";
}

/** Replaces a value type whole. Refused with `ValueTypeReferencedError` for a base type in use. */
export async function updateKnowledgeNetworkValueType(
  networkId: string,
  valueTypeId: string,
  input: ValueTypeInput,
) {
  if (useMock) {
    const stored = mockValueTypes[networkId]?.find((item) => item.id === valueTypeId);
    const references = mockReferences(networkId, valueTypeId);
    if (stored && stored.baseType !== input.baseType && references.length) {
      throw new ValueTypeReferencedError(VALUE_TYPE_REFERENCED_CODE, references);
    }
    saveMock(networkId, valueTypeId, input);
    await wait(undefined);
    return;
  }

  try {
    await http.put(
      `${valueTypesPath(networkId)}/${encodeURIComponent(valueTypeId)}`,
      { ...toBackendValueTypeInput(input), id: valueTypeId },
      { skipErrorToast: true },
    );
  } catch (error) {
    rethrowValueTypeError(error);
  }
}

/** Deletes a value type. Refused with `ValueTypeReferencedError` while a property names it. */
export async function deleteKnowledgeNetworkValueType(networkId: string, valueTypeId: string) {
  if (useMock) {
    const references = mockReferences(networkId, valueTypeId);
    if (references.length) {
      throw new ValueTypeReferencedError(VALUE_TYPE_REFERENCED_CODE, references);
    }
    mockValueTypes[networkId] = (mockValueTypes[networkId] ?? []).filter(
      (item) => item.id !== valueTypeId,
    );
    await wait(undefined);
    return;
  }

  try {
    await http.delete(`${valueTypesPath(networkId)}/${encodeURIComponent(valueTypeId)}`, {
      skipErrorToast: true,
    });
  } catch (error) {
    rethrowValueTypeError(error);
  }
}
